    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        String codigo = txtCodigo.getText().trim();
        String contrasena = txtContrasena.getText().trim();
        
        if (codigo.isEmpty() || contrasena.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "Debe completar todos los campos");
            return;
        }
        
        if (!contrasena.equals("13311331")){
            javax.swing.JOptionPane.showMessageDialog(this, "Contraseña incorrecta");
            return;
        }
        modelo.Estudiante estudiante = servicio.Datos.estudiantes.buscar(codigo);

        if (estudiante != null){
            servicio.Datos.matriculas.eliminarPorCodigo(codigo);
            servicio.Datos.notas.eliminarNotas(codigo);
            servicio.Datos.estudiantes.eliminar(codigo);
            
            javax.swing.JOptionPane.showMessageDialog(this, "Estudiante, matrícula y notas eliminadas correctamente");

            txtCodigo.setText("");
            txtContrasena.setText("");
            return;
        }
        
        modelo.Docente docente = servicio.Datos.docentes.buscarPorCodigo(codigo);
        if (docente != null){
            servicio.Datos.docentes.eliminar(codigo);
            javax.swing.JOptionPane.showMessageDialog(this, "Docente eliminado correctamente");
            txtCodigo.setText("");
            txtContrasena.setText("");
            return;
        }
        
        javax.swing.JOptionPane.showMessageDialog(this, "No se encontró un estudiante o docente con ese código");
    }//GEN-LAST:event_btnEliminarActionPerformed

