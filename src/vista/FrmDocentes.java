    private void btnRegistrar3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrar3ActionPerformed
        String nombre = txtNombre.getText().trim();
        String apellido = txtApellidos.getText().trim();
        String dni = txtDNI.getText().trim();
        String especialidad = txtEspecialidad.getText().trim();
        String textoIndice = txtIndice.getText().trim();
        if (nombre.isEmpty() || apellido.isEmpty() || dni.isEmpty() || especialidad.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "Debe completar todos los datos del docente");
            return;
        }
        if (textoIndice.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "Ingrese el índice donde desea registrar");
            return;
        }
        int indice;
        
        try{
            indice = Integer.parseInt(textoIndice);
        }catch(NumberFormatException e){
            javax.swing.JOptionPane.showMessageDialog(this, "El índice debe ser un número entero");
            return;
        }
        if (indice < 0 || indice > servicio.Datos.docentes.cantidad()){
            javax.swing.JOptionPane.showMessageDialog(this, "Índice inválido");
    return;
}

        String codigo = servicio.Datos.generarCodigoDocente();
        modelo.Docente docente = new modelo.Docente(codigo, nombre, apellido, dni, especialidad);
        boolean registrado = servicio.Datos.docentes.registrarIndice(indice, docente);

        if (registrado){
            javax.swing.JOptionPane.showMessageDialog(this, "Docente registrado correctamente.\nCódigo generado: " + codigo);
            txtNombre.setText("");
            txtApellidos.setText("");
            txtDNI.setText("");
            txtEspecialidad.setText("");
            txtIndice.setText("");
        }else{
            javax.swing.JOptionPane.showMessageDialog(this, "No se pudo registrar al docente");
}
    }//GEN-LAST:event_btnRegistrar3ActionPerformed

    private void btnRegistrar1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrar1ActionPerformed
        String nombre = txtNombre.getText().trim();
        String apellido = txtApellidos.getText().trim();
        String dni = txtDNI.getText().trim();
        String especialidad = txtEspecialidad.getText().trim();
        
        if (!dni.matches("\\d{8}")){
            javax.swing.JOptionPane.showMessageDialog(this, "El DNI debe tener exactamente 8 números");
            return;
        }

        if (servicio.Datos.docentes.buscarPorDni(dni) != null){
            javax.swing.JOptionPane.showMessageDialog(this, "Ya existe un docente registrado con ese DNI");
            return;
        }
        
        if (servicio.Datos.estudiantes.buscarPorDni(dni) != null){
            javax.swing.JOptionPane.showMessageDialog(this, "Ese DNI ya pertenece a un estudiante");
            return;
        }
        

        if (nombre.isEmpty() || apellido.isEmpty() || dni.isEmpty() || especialidad.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "Debe completar todos los campos");
            return;
        }
        String codigo = servicio.Datos.generarCodigoDocente();
        
        modelo.Docente docente = new modelo.Docente(codigo, nombre, apellido, dni, especialidad);
        servicio.Datos.docentes.registrarInicio(docente);
        javax.swing.JOptionPane.showMessageDialog(this, "Docente registrado correctamente.\n"
                + "Código generado: " + codigo);
        
        txtNombre.setText("");
        txtApellidos.setText("");
        txtDNI.setText("");
        txtEspecialidad.setText("");
        txtIndice.setText("");
    }//GEN-LAST:event_btnRegistrar1ActionPerformed

