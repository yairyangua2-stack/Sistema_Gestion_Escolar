    private void btnCalificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalificarActionPerformed
        String codigo = txtCalificar.getText().trim();
        
        if (codigo.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "Ingrese el código del estudiante");
            return;
        }

        estudianteEncontrado = servicio.Datos.estudiantes.buscar(codigo);

        if (estudianteEncontrado == null){
            javax.swing.JOptionPane.showMessageDialog(this, "No se encontró un estudiante con ese código");
            bloquearCampos();
            return;
        }
        
        habilitarCampos();
        javax.swing.JOptionPane.showMessageDialog(this, "Estudiante encontrado: " 
                + estudianteEncontrado.getNombreCompleto());
        double[] notasGuardadas = servicio.Datos.notas.obtenerNotas(codigo);

        if (notasGuardadas != null){
            mostrarNotasGuardadas(notasGuardadas);
        }else{
            limpiarNotas();
        }
    }//GEN-LAST:event_btnCalificarActionPerformed

    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
        if (estudianteEncontrado == null){
            javax.swing.JOptionPane.showMessageDialog(this, "Primero debe buscar un estudiante");
            return;
        }

        if (txtComunicacionE1.getText().trim().isEmpty() ||
                txtComunicacionE2.getText().trim().isEmpty() || txtComunicacionP.getText().trim().isEmpty() ||
                txtMatematicasE1.getText().trim().isEmpty() || txtMatematicasE2.getText().trim().isEmpty() ||
                txtMatematicasP.getText().trim().isEmpty() || txtCYTE1.getText().trim().isEmpty() ||
                txtInglesE1.getText().trim().isEmpty() || txtInglesE2.getText().trim().isEmpty() ||
                txtInglesP.getText().trim().isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "Debe ingresar todas las notas");
            return;
        }

        double[] notas = new double[12];

        try{
            notas[0] = Double.parseDouble(txtComunicacionE1.getText().trim());
            notas[1] = Double.parseDouble(txtComunicacionE2.getText().trim());
            notas[2] = Double.parseDouble(txtComunicacionP.getText().trim());
            notas[3] = Double.parseDouble(txtMatematicasE1.getText().trim());
            notas[4] = Double.parseDouble(txtMatematicasE2.getText().trim());
            notas[5] = Double.parseDouble(txtMatematicasP.getText().trim());
            notas[6] = Double.parseDouble(txtCYTE1.getText().trim());
            notas[7] = Double.parseDouble(txtCYTE2.getText().trim());
            notas[8] = Double.parseDouble(txtCYTP.getText().trim());
            notas[9] = Double.parseDouble(txtInglesE1.getText().trim());
            notas[10] = Double.parseDouble(txtInglesE2.getText().trim());
            notas[11] = Double.parseDouble(txtInglesP.getText().trim());
        }catch(NumberFormatException e){
            javax.swing.JOptionPane.showMessageDialog(this, "Las notas deben ser números");
            return;
        }
        
        for (int i = 0; i < notas.length; i++){
            if (notas[i] < 0 || notas[i] > 20){
                javax.swing.JOptionPane.showMessageDialog(this, "Todas las notas deben estar entre 0 y 20");
        return;
    }
}
        
        boolean registrado = servicio.Datos.notas.registrarNotas(estudianteEncontrado.getCodigo(),
        estudianteEncontrado.getNombreCompleto(),notas);

        if (registrado){
            calcularEvaluacionesFinales();
            javax.swing.JOptionPane.showMessageDialog(this, "Notas registradas correctamente");

        }else{
            javax.swing.JOptionPane.showMessageDialog(this, "No se pudieron registrar las notas");
        }
    }//GEN-LAST:event_btnIngresarActionPerformed

