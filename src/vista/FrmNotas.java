    private void calcularEvaluacionesFinales(){

    try{
        double comunicacion = (Double.parseDouble(txtComunicacionE1.getText()) +
                Double.parseDouble(txtComunicacionE2.getText()) +
                Double.parseDouble(txtComunicacionP.getText())) / 3;

        double matematicas = (Double.parseDouble(txtMatematicasE1.getText()) +
                Double.parseDouble(txtMatematicasE2.getText()) +
                Double.parseDouble(txtMatematicasP.getText())) / 3;

        double cyt = (Double.parseDouble(txtCYTE1.getText()) +
                Double.parseDouble(txtCYTE2.getText()) +
                Double.parseDouble(txtCYTP.getText())) / 3;

        double ingles = (Double.parseDouble(txtInglesE1.getText()) +
                Double.parseDouble(txtInglesE2.getText()) +
                Double.parseDouble(txtInglesP.getText())) / 3;

        txtComunicacionEF.setText(String.format("%.2f", comunicacion));
        txtMatematicasEF.setText(String.format("%.2f", matematicas));
        txtCYTEF.setText(String.format("%.2f", cyt));
        txtInglesEF.setText(String.format("%.2f", ingles));

    }catch(NumberFormatException e){

    }
}

