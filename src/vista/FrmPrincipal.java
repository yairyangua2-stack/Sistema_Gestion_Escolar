    private void btnBuscarMActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarMActionPerformed
        String nombre = txtBuscarM.getText().trim();
        if (nombre.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this,"Ingrese el nombre del alumno");
    return;
}
        modelo.Matricula matricula = servicio.Datos.matriculas.buscarPorNombre(nombre);


        if (matricula != null){
            taMostrarM.setText(matricula.toString() );
        } else {
            javax.swing.JOptionPane.showMessageDialog( this,"Alumno no encontrado"
    );
}
    }//GEN-LAST:event_btnBuscarMActionPerformed

