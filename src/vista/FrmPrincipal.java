    private void btnBuscarDActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarDActionPerformed
        String nombre = txtBuscarD.getText().trim();
        
        if (nombre.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "Ingrese el nombre del docente");
    return;
}

        modelo.Docente docente = servicio.Datos.docentes.buscarPorNombre(nombre);

        if (docente != null){
            taMostrarD.setText(docente.toString());
        }else{
            javax.swing.JOptionPane.showMessageDialog(this, "Docente no encontrado");
        }
    }//GEN-LAST:event_btnBuscarDActionPerformed

