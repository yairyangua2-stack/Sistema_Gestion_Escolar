    private void txtEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtEditarActionPerformed
        String codigo = txtEditar.getText().trim();
        if (codigo.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "Ingrese el código del estudiante");
            return;
        }

        estudianteEncontrado = servicio.Datos.estudiantes.buscar(codigo);

        if (estudianteEncontrado == null){
            javax.swing.JOptionPane.showMessageDialog(this, "No se encontró un estudiante con ese código");
        }
        txtNombreM.setEnabled(true);
        txtApellidosM.setEnabled(true);
        txtGradoM.setEnabled(true);
        txtSeccionM.setEnabled(true);
        btnModificar.setEnabled(true);
        txtNombreM.setText(estudianteEncontrado.getNombre());
        txtApellidosM.setText(estudianteEncontrado.getApellido());
        txtDNIM.setText(estudianteEncontrado.getDni());
        txtGradoM.setText(estudianteEncontrado.getGrado());
        txtSeccionM.setText(estudianteEncontrado.getSeccion());
    }//GEN-LAST:event_txtEditarActionPerformed

