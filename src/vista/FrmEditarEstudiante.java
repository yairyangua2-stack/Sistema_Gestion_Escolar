    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        if (estudianteEncontrado == null){
            javax.swing.JOptionPane.showMessageDialog(this, "Primero debe buscar un estudiante");
            return;
        }
        String nombre = txtNombreM.getText().trim();
        String apellido = txtApellidosM.getText().trim();
        String dni = txtDNIM.getText().trim();
        String grado = txtGradoM.getText().trim();
        String seccion = txtSeccionM.getText().trim();
        if (nombre.isEmpty() || apellido.isEmpty() || dni.isEmpty() || grado.isEmpty() || seccion.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "Debe completar todos los campos");
            return;
        }
        modelo.Estudiante nuevo = new modelo.Estudiante(estudianteEncontrado.getCodigo(),nombre,apellido,
        dni, grado, seccion);
        
        boolean modificado = servicio.Datos.estudiantes.editar(estudianteEncontrado.getCodigo(), nuevo);
        
        if (modificado){
            javax.swing.JOptionPane.showMessageDialog(this, "Datos modificados correctamente");
            txtNombreM.setEnabled(false);
            txtApellidosM.setEnabled(false);
            txtDNIM.setEnabled(false);
            txtGradoM.setEnabled(false);
            txtSeccionM.setEnabled(false);
            btnModificar.setEnabled(false);
            
            txtEditar.setText("");
            txtNombreM.setText("");
            txtApellidosM.setText("");
            txtDNIM.setText("");
            txtGradoM.setText("");
            txtSeccionM.setText("");
        }else{
            javax.swing.JOptionPane.showMessageDialog(this, "No se pudieron modificar los datos");
        }
    }//GEN-LAST:event_btnModificarActionPerformed

