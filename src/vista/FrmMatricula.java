    private void btnMatricularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMatricularActionPerformed
        String nombre = txtNombreM.getText().trim();
        String apellido = txtApellidosM.getText().trim();
        String dni = txtDNIM.getText().trim();
        String grado = txtGradoM.getText().trim();
        String seccion = txtSeccionM.getText().trim();
        
        if (servicio.Datos.estudiantes.buscarPorDni(dni) != null){
            javax.swing.JOptionPane.showMessageDialog(this, "Ya existe un estudiante registrado con ese DNI");
            return;
        }
        
        if (servicio.Datos.docentes.buscarPorDni(dni) != null){
            javax.swing.JOptionPane.showMessageDialog(this, "Ese DNI ya pertenece a un docente");
            return;
        }
        if (!dni.matches("\\d{8}")){
            javax.swing.JOptionPane.showMessageDialog(this, "El DNI debe tener exactamente 8 números");
            return;
        }

        if (nombre.isEmpty() || apellido.isEmpty() || dni.isEmpty() || grado.isEmpty() || seccion.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,"Debe completar todos los campos");
            return;
        }

        String codigo =servicio.Datos.generarCodigoEstudiante(); 
        modelo.Estudiante estudiante = new modelo.Estudiante(codigo, nombre, apellido, dni, grado, seccion);

        boolean registrado = servicio.Datos.estudiantes.registrar(estudiante);


        if (registrado){
            servicio.Datos.matriculas.matricular(estudiante,null);
            javax.swing.JOptionPane.showMessageDialog(this,"Estudiante matriculado correctamente.\n"
            + "Código generado: "
            + codigo
    );
    
            txtNombreM.setText("");
            txtApellidosM.setText("");
            txtDNIM.setText("");
            txtGradoM.setText("");
            txtSeccionM.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this,"No se pudo registrar el estudiante"
    );
}
    }//GEN-LAST:event_btnMatricularActionPerformed

